// 生成 src/plugins.generated.ts：扫描 plugins/*/fe 中带 "llplugin": true 的包，
// 产出壳层用的注册函数。壳层源码永远不 import 具体插件实现。
// 新增插件 = 创建 plugins/<id>/{manifest.json, be/, fe/} 后运行 `npm run gen`。
import { readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";

const root = process.cwd();
const pluginsDir = path.join(root, "plugins");
const entries = [];

for (const dirent of readdirSync(pluginsDir, { withFileTypes: true })) {
  if (!dirent.isDirectory()) continue;
  const pkgPath = path.join(pluginsDir, dirent.name, "fe", "package.json");
  if (!existsSync(pkgPath)) continue;
  const pkg = JSON.parse(readFileSync(pkgPath, "utf8"));
  if (!pkg.llplugin) continue;
  entries.push({
    id: dirent.name,
    pkgName: pkg.name,
    version: pkg.version || "0.0.0",
  });
}

entries.sort((a, b) => a.pkgName.localeCompare(b.pkgName));

const ident = (id) => id.replace(/-/g, "_");
const imports = entries
  .map((e) => `import { setup as setup_${ident(e.id)} } from "${e.pkgName}";`)
  .join("\n");
const calls = entries
  .map((e) => `  setup_${ident(e.id)}();`)
  .join("\n");

const out = `// AUTO-GENERATED by tools/gen-frontend-registry.mjs — DO NOT EDIT
// 插件清单：${entries.map((e) => `${e.pkgName}@${e.version}`).join(", ") || "(none)"}
${imports}

/**
 * 注册全部前端插件包（plugins/<id>/fe）。
 */
export function registerBuiltinPlugins(): void {
${calls}
}
`;

writeFileSync(path.join(root, "src", "plugins.generated.ts"), out);
console.log(`[gen] plugins.generated.ts: ${entries.length} plugin(s) — ${entries.map((e) => e.id).join(", ")}`);
